import { h } from "../lib/dom";
import type { ProvenanceKind, ProvenanceNote } from "../app/types";

// Glyph + word, never color alone, so the label survives color-blindness and grayscale.
export const PROVENANCE: Record<ProvenanceKind, { glyph: string; label: string; meaning: string }> = {
  schematic: {
    glyph: "\u25C7",
    label: "Schematic",
    meaning: "A conceptual illustration. Structure or values are chosen to explain an idea, not taken from data.",
  },
  computed: {
    glyph: "\u25A3",
    label: "Computed",
    meaning: "Numbers calculated exactly from the inputs shown, using a documented formula.",
  },
  simulated: {
    glyph: "\u223F",
    label: "Simulated",
    meaning: "Generated by a model with stated assumptions. It is not an observation.",
  },
  measured: {
    glyph: "\u25CF",
    label: "Measured",
    meaning: "Comes from recorded data in a cited public dataset.",
  },
};

export function provenanceBadge(kind: ProvenanceKind): HTMLElement {
  const p = PROVENANCE[kind];
  return h("span", { class: `badge badge--${kind}`, title: p.meaning }, h("span", { "aria-hidden": "true" }, p.glyph), ` ${p.label}`);
}

export function provenanceList(notes: ProvenanceNote[]): HTMLElement {
  return h(
    "ul",
    { class: "prov-list" },
    ...notes.map((n) => h("li", {}, provenanceBadge(n.kind), h("strong", {}, ` ${n.aspect}: `), n.note)),
  );
}
